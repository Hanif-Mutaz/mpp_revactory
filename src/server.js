import path from 'node:path';
import {fileURLToPath} from 'node:url';
import express from 'express';
import helmet from 'helmet';
import {env} from './config/env.js';
import {pool} from './db/pool.js';
import {requestContext} from './middleware/request.js';
import {auth} from './middleware/auth.js';
import {errorHandler} from './middleware/error.js';
import {authRouter} from './modules/auth/router.js';
import {employeesRouter} from './modules/employees/router.js';
import {linesRouter} from './modules/lines/router.js';
import {skillsRouter} from './modules/skills/router.js';
import {planningRouter} from './modules/planning/router.js';
import {attendanceRouter} from './modules/attendance/router.js';
import {waitingRouter} from './modules/waiting/router.js';
import {approvalsRouter} from './modules/approvals/router.js';
import {settingsRouter} from './modules/settings/router.js';
import {sharedRouter} from './modules/shared/router.js';
import {reportsRouter} from './modules/reports/router.js';
import {auditRouter} from './modules/audit/router.js';
import {devicesRouter} from './modules/devices/router.js';
import {absencesRouter} from './modules/absences/router.js';
import {importsRouter} from './modules/imports/router.js';
import {backupRouter} from './modules/backup/router.js';

const app=express();
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],styleSrc:["'self'","'unsafe-inline'"],scriptSrc:["'self'","'unsafe-inline'"],imgSrc:["'self'","data:"],connectSrc:["'self'"]}}}));
app.use(express.json({limit:'2mb'}));
app.use(requestContext);
app.get('/health',async(_req,res)=>{await pool.query('select 1');res.json({ok:true,data:{status:'UP',time:new Date().toISOString()}})});
app.use('/api/auth',authRouter);
app.use('/api/employees',auth,employeesRouter);
app.use('/api/lines',auth,linesRouter);
app.use('/api/skills',auth,skillsRouter);
app.use('/api/plans',auth,planningRouter);
app.use('/api/attendance',auth,attendanceRouter);
app.use('/api/waiting',auth,waitingRouter);
app.use('/api/approvals',auth,approvalsRouter);
app.use('/api/settings',auth,settingsRouter);
app.use('/api/shared-cell-leaders',auth,sharedRouter);
app.use('/api/reports',auth,reportsRouter);
app.use('/api/audit',auth,auditRouter);
app.use('/api/devices',auth,devicesRouter);
app.use('/api/absences',auth,absencesRouter);
app.use('/api/imports',auth,importsRouter);
app.use('/api/backup',auth,backupRouter);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../public');
app.use(express.static(root,{maxAge:env.nodeEnv==='production'?'1h':0}));
app.get('*path',(_req,res)=>res.sendFile(path.join(root,'index.html')));
app.use(errorHandler);
app.listen(env.port,'0.0.0.0',()=>console.log(`MPP listening on :${env.port}`));
